#!/usr/bin/env python3
"""Generates gore models: blood droplet, flesh chunk, bone chunk, blood pool.

Outputs (next to this script): gore.inc.c (group0 display lists), gore_geo.inc.c (geo layouts)
and gore_externs.h (pasted into actors/group0.h).
"""
import math, os, random

HERE = os.path.dirname(os.path.abspath(__file__))
out = ["// Gore models - generated by gen_gore.py. Do not edit by hand.\n"]
rng = random.Random(1234)  # deterministic lumps

def nb(v): return int(round(max(-1, min(1, v)) * 127)) & 0xFF

def unlit(name, verts, tris, rgb, cull=False):
    out.append(f"static const Vtx {name}_vtx[] = {{\n" + "\n".join(
        f"    {{{{{{ {int(round(x))}, {int(round(y))}, {int(round(z))} }}, 0, {{ 0, 0 }}, {{ 0xff, 0xff, 0xff, 0xff }}}}}},"
        for x, y, z in verts) + "\n};\n")
    lines = []
    for i in range(0, len(verts), 16):
        chunk = [t for t in tris if all(i <= v < i + 16 for v in t)]
        lines.append(f"    gsSPVertex({name}_vtx + {i}, {min(16, len(verts) - i)}, 0),")
        for t in chunk:
            lines.append(f"    gsSP1Triangle({t[0] - i}, {t[1] - i}, {t[2] - i}, 0x0),")
    cull_off = "" if cull else "    gsSPClearGeometryMode(G_CULL_BACK),\n"
    cull_on = "" if cull else "    gsSPSetGeometryMode(G_CULL_BACK),\n"
    out.append(f"const Gfx {name}[] = {{\n    gsDPPipeSync(),\n    gsSPTexture(0xFFFF, 0xFFFF, 0, G_TX_RENDERTILE, G_OFF),\n"
               f"    gsDPSetCombineMode(G_CC_PRIMITIVE, G_CC_PRIMITIVE),\n    gsDPSetPrimColor(0, 0, {rgb[0]}, {rgb[1]}, {rgb[2]}, 255),\n"
               + cull_off + "\n".join(lines) + "\n    gsDPPipeSync(),\n" + cull_on +
               "    gsDPSetCombineMode(G_CC_SHADE, G_CC_SHADE),\n    gsSPEndDisplayList(),\n};\n")

def lit(name, verts, norms, tris, rgb):
    """verts/norms per index; tris must only reference vertices within 16-vertex windows."""
    r, g, b = rgb
    out.append(f"static const Lights1 {name}_lights = gdSPDefLights1(0x{r//2:02x}, 0x{g//2:02x}, 0x{b//2:02x}, 0x{r:02x}, 0x{g:02x}, 0x{b:02x}, 0x28, 0x28, 0x28);\n")
    # flatten into per-triangle vertices so any mesh packs into 15-vertex loads
    flat_v, flat_t = [], []
    for t in tris:
        base = len(flat_v)
        for k in t:
            flat_v.append((verts[k], norms[k]))
        flat_t.append((base, base + 1, base + 2))
    out.append(f"static const Vtx {name}_vtx[] = {{\n" + "\n".join(
        f"    {{{{{{ {int(round(p[0]))}, {int(round(p[1]))}, {int(round(p[2]))} }}, 0, {{ 0, 0 }}, {{ 0x{nb(n[0]):02x}, 0x{nb(n[1]):02x}, 0x{nb(n[2]):02x}, 0xff }}}}}},"
        for p, n in flat_v) + "\n};\n")
    lines = []
    for i in range(0, len(flat_t), 5):
        group = flat_t[i:i + 5]
        lines.append(f"    gsSPVertex({name}_vtx + {group[0][0]}, {len(group) * 3}, 0),")
        for j, _ in enumerate(group):
            lines.append(f"    gsSP1Triangle({j * 3}, {j * 3 + 1}, {j * 3 + 2}, 0x0),")
    out.append(f"const Gfx {name}[] = {{\n    gsDPPipeSync(),\n    gsSPTexture(0xFFFF, 0xFFFF, 0, G_TX_RENDERTILE, G_OFF),\n"
               f"    gsDPSetCombineMode(G_CC_SHADE, G_CC_SHADE),\n    gsSPLight(&{name}_lights.l, 1),\n    gsSPLight(&{name}_lights.a, 2),\n"
               + "\n".join(lines) + "\n    gsSPEndDisplayList(),\n};\n")

def blob(radii, lat, lon, jitter):
    verts, norms, idx = [], [], {}
    def v(i, j):
        key = (i, j % lon)
        if i in (0, lat): key = (i, 0)
        if key not in idx:
            th = math.pi * key[0] / lat; ph = 2 * math.pi * key[1] / lon
            u = (math.sin(th) * math.cos(ph), math.cos(th), math.sin(th) * math.sin(ph))
            s = 1.0 + (rng.uniform(-jitter, jitter) if 0 < key[0] < lat else 0)
            verts.append(tuple(u[k] * radii[k] * s for k in range(3)))
            norms.append(u)
            idx[key] = len(verts) - 1
        return idx[key]
    tris = []
    for i in range(lat):
        for j in range(lon):
            a, b2, c, d = v(i, j), v(i, j + 1), v(i + 1, j), v(i + 1, j + 1)
            if i != 0: tris.append((a, c, b2))
            if i != lat - 1: tris.append((b2, c, d))
    return verts, norms, tris

# blood droplet: small double-sided diamond, bright red
dv = [(0, 7, 0), (0, -5, 0), (4, 0, 0), (-4, 0, 0), (0, 0, 4), (0, 0, -4)]
dt = [(0, 2, 4), (0, 4, 3), (0, 3, 5), (0, 5, 2), (1, 4, 2), (1, 3, 4), (1, 5, 3), (1, 2, 5)]
unlit("gore_blood_drop_dl", dv, dt, (175, 8, 8))

# flesh chunk: lumpy lit blob
v, n, t = blob((13, 9, 11), 4, 7, 0.35)
lit("gore_gib_flesh_dl", v, n, t, (0xA4, 0x14, 0x18))

# bone chunk: shaft + two knobs
bv, bn, btri = [], [], []
def add_blob(center, radii, lat, lon):
    vv, nn, tt = blob(radii, lat, lon, 0.1)
    base = len(bv)
    bv.extend(tuple(p[k] + center[k] for k in range(3)) for p in vv); bn.extend(nn)
    btri.extend(tuple(i + base for i in tri) for tri in tt)
add_blob((0, 0, 0), (16, 3.5, 3.5), 3, 6)
add_blob((15, 0, 0), (5, 5, 5), 3, 6)
add_blob((-15, 0, 0), (5, 5, 5), 3, 6)
lit("gore_gib_bone_dl", bv, bn, btri, (0xE8, 0xDE, 0xC6))

# blood pool: irregular flat disc on the XZ plane, radius ~100 (scaled per object)
pv = [(0, 0, 0)]
segs = 14
for k in range(segs):
    a = 2 * math.pi * k / segs
    r = 100 * rng.uniform(0.75, 1.15)
    pv.append((math.cos(a) * r, 0, math.sin(a) * r))
pt = [(0, 1 + (k + 1) % segs, 1 + k) for k in range(segs)]
unlit("gore_blood_pool_dl", pv, pt, (105, 4, 6), cull=True)

open(os.path.join(HERE, 'gore.inc.c'), 'w').write("\n".join(out))

geo = ["// Gore geo layouts - generated by gen_gore.py. Do not edit by hand.\n"]
for name, dl, layer, radius in (('gore_blood_drop_geo', 'gore_blood_drop_dl', 'LAYER_OPAQUE', 50),
                                ('gore_gib_flesh_geo', 'gore_gib_flesh_dl', 'LAYER_OPAQUE', 80),
                                ('gore_gib_bone_geo', 'gore_gib_bone_dl', 'LAYER_OPAQUE', 80),
                                ('gore_blood_pool_geo', 'gore_blood_pool_dl', 'LAYER_OPAQUE_DECAL', 400)):
    geo += [f"const GeoLayout {name}[] = {{", f"    GEO_CULLING_RADIUS({radius}),", "    GEO_OPEN_NODE(),",
            f"        GEO_DISPLAY_LIST({layer}, {dl}),", "    GEO_CLOSE_NODE(),", "    GEO_END(),", "};\n"]
open(os.path.join(HERE, 'gore_geo.inc.c'), 'w').write("\n".join(geo))

ext = ["extern const Gfx gore_blood_drop_dl[];", "extern const Gfx gore_gib_flesh_dl[];", "extern const Gfx gore_gib_bone_dl[];",
       "extern const Gfx gore_blood_pool_dl[];", "extern const GeoLayout gore_blood_drop_geo[];", "extern const GeoLayout gore_gib_flesh_geo[];",
       "extern const GeoLayout gore_gib_bone_geo[];", "extern const GeoLayout gore_blood_pool_geo[];"]
open(os.path.join(HERE, 'gore_externs.h'), 'w').write("// generated by gen_gore.py\n" + "\n".join(ext) + "\n")
print("wrote gore.inc.c, gore_geo.inc.c, gore_externs.h")
